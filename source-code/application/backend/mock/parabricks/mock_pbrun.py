def generate_vcf(patient_id: str, sample_id: str, num_variants: int = 50, deepvariant: bool = False) -> str:
    random.seed(sample_id)
    rng = random.Random(sample_id)

    N_LIVE      = 30
    N_STATIC    = 20
    N_PATHOGENIC_LIVE   = 2
    N_PATHOGENIC_STATIC = random.randint(1, 2)

    live = fetch_live_variants(rng, n_total=N_LIVE, n_pathogenic=N_PATHOGENIC_LIVE)
    live_count = len(live)
    print(f"[MOCK] myvariant.info returned {live_count} live variants")

    n_static_needed = (50 - live_count)
    n_path_static   = min(N_PATHOGENIC_STATIC, len(PATHOGENIC_VARIANTS))
    n_other_static  = max(0, n_static_needed - n_path_static)

    static_pathogenic = random.sample(PATHOGENIC_VARIANTS, n_path_static)
    static_other      = random.sample(OTHER_VARIANTS, min(n_other_static, len(OTHER_VARIANTS)))
    static_variants   = static_pathogenic + static_other

    selected = live + static_variants
    selected.sort(key=lambda v: (v[0], v[1]))

    header = VCF_HEADER_DEEPVARIANT if deepvariant else VCF_HEADER_FQ2BAM
    lines = [header]

    for chrom, pos, ref, alt, gene, qual, filt in selected:
        depth = random.randint(30, 200)
        af = round(random.uniform(0.1, 0.9), 3)
        gt = random.choice(["0/1", "1/1"])

        if deepvariant:
            dvq = round(qual + random.uniform(-5, 10), 1)
            info = f"DP={depth};AF={af};DVQ={dvq}"
            gq = random.randint(20, 99)
            lines.append(f"{chrom}	{pos}	.	{ref}	{alt}	{qual:.1f}	{filt}	{info}	GT:DP:GQ	{gt}:{depth}:{gq}")
        else:
            info = f"DP={depth};AF={af}"
            lines.append(f"{chrom}	{pos}	.	{ref}	{alt}	{qual:.1f}	{filt}	{info}	GT:DP	{gt}:{depth}")
    
    random.seed()
    
    return "\n".join(lines) + "\n"


def run_fq2bam(args):
    print(f"[MOCK] Parabricks fq2bam starting")
    print(f"[MOCK] Input FASTQ: {args.in_fq}")
    print(f"[MOCK] Reference: {args.ref}")
    print(f"[MOCK] Output BAM: {args.out_bam}")

    stages = [
        ("Loading reference genome", 10),
        ("Aligning reads (BWA-MEM2)", 20),
        ("Sorting alignments", 5),
        ("Marking duplicates", 5),
        ("Base quality recalibration", 10),
        ("Writing BAM", 5),
    ]

    for stage_name, duration in stages:
        print(f"[MOCK] {stage_name}...")
        time.sleep(duration)

    bam_path = Path(args.out_bam)
    bam_path.parent.mkdir(parents=True, exist_ok=True)
    bam_path.write_text("MOCK_BAM_FILE\n")

    print(f"[MOCK] BAM written to: {bam_path}")
    print(f"[MOCK] Parabricks fq2bam complete")


def run_deepvariant(args):
    print(f"[MOCK] Parabricks DeepVariant starting")
    print(f"[MOCK] Input BAM: {args.in_bam}")
    print(f"[MOCK] Output VCF: {args.out_variants}")

    stages = [
        ("Loading model weights", 10),
        ("Making pileup examples", 15),
        ("Calling variants (DeepVariant CNN)", 20),
        ("Genotyping variants", 10),
        ("Writing VCF", 5),
    ]

    for stage_name, duration in stages:
        print(f"[MOCK] {stage_name}...")
        time.sleep(duration)

    vcf_path = Path(args.out_variants)
    vcf_path.parent.mkdir(parents=True, exist_ok=True)

    sample_id = vcf_path.stem
    patient_id = vcf_path.parent.parent.name
    
    vcf_content = generate_vcf(patient_id, sample_id, args.num_variants, deepvariant=True)
    vcf_path.write_text(vcf_content)

    variant_count = sum(1 for line in vcf_content.splitlines() if not line.startswith("#"))
    print(f"[MOCK] DeepVariant called {variant_count} variants")
    print(f"[MOCK] VCF written to: {vcf_path}")
    print(f"[MOCK] Parabricks DeepVariant complete")


