MYVARIANT_URL = "https://myvariant.info/v1/query"
MYVARIANT_FIELDS = "chrom,vcf.position,vcf.ref,vcf.alt,clinvar.gene.symbol"
MYVARIANT_TIMEOUT = 12

QUERY_PATHOGENIC = "clinvar.rcv.clinical_significance:Pathogenic AND _exists_:vcf"
QUERY_OTHER = (
    "(clinvar.rcv.clinical_significance:Benign"
    " OR clinvar.rcv.clinical_significance:\"Likely benign\""
    " OR clinvar.rcv.clinical_significance:\"Uncertain significance\")"
    " AND _exists_:vcf"
)


def _myvariant_query(q: str, size: int, offset: int) -> list[tuple]:
    url = (
        f"{MYVARIANT_URL}"
        f"?q={quote(q)}"
        f"&fields={MYVARIANT_FIELDS}"
        f"&size={size}"
        f"&from={offset}"
        f"&assembly=hg38"
    )
    with urlopen(url, timeout=MYVARIANT_TIMEOUT) as resp:
        data = json.loads(resp.read())

    results = []
    for hit in data.get("hits", []):
        vcf = hit.get("vcf") or {}
        pos = vcf.get("position")
        ref = vcf.get("ref")
        alt = vcf.get("alt")
        gene = (hit.get("clinvar") or {}).get("gene", {}).get("symbol")
        chrom = hit.get("chrom")
        if not all([pos, ref, alt, gene, chrom]):
            continue
        if len(ref) > 10 or len(alt) > 10:
            continue
        results.append((f"chr{chrom}", int(pos), ref, alt, gene))
    return results


def fetch_live_variants(rng: random.Random, n_total: int = 30, n_pathogenic: int = 2) -> list[tuple]:
    variants: list[tuple] = []

    path_offset = rng.randint(0, 5000)
    try:
        raw = _myvariant_query(QUERY_PATHOGENIC, n_pathogenic * 4, path_offset)
        sampled = rng.sample(raw, min(n_pathogenic, len(raw)))
        variants.extend(sampled)
        print(f"[MOCK] myvariant.info: fetched {len(sampled)} pathogenic variants (offset={path_offset})")
    except Exception as exc:
        print(f"[MOCK] myvariant.info pathogenic fetch failed: {exc}")

    n_remaining = n_total - len(variants)
    if n_remaining > 0:
        other_offset = rng.randint(0, 5000)
        try:
            raw = _myvariant_query(QUERY_OTHER, n_remaining * 3, other_offset)
            sampled = rng.sample(raw, min(n_remaining, len(raw)))
            variants.extend(sampled)
            print(f"[MOCK] myvariant.info: fetched {len(sampled)} other variants (offset={other_offset})")
        except Exception as exc:
            print(f"[MOCK] myvariant.info other fetch failed: {exc}")

    for i, v in enumerate(variants):
        qual = round(rng.uniform(50.0, 99.9), 1)
        filt = rng.choices(["PASS", "LowQual"], weights=[3, 1])[0]
        variants[i] = (*v, qual, filt)

    return variants


